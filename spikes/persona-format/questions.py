def expected(question_id: str, p: dict) -> str | set | None:
    """기대 선택지. 여러 개가 허용되면 set. 뚜렷하지 않으면 None"""
    t = p['traits']
    if question_id == 'love':
        if t['risk'] >= 65 and t['caution'] <= 50:
            return '먼저 고백한다'
        if t['caution'] >= 65 and t['risk'] <= 50:
            return '좀 더 지켜본다'
        return None
    if question_id == 'spend':
        if t['spending'] >= 65 and t['caution'] <= 50:
            return '할부로 지금 산다'
        if t['caution'] >= 65 or t['spending'] <= 35:
            return '모아서 나중에 산다'
        return None
    if question_id == 'job':
        if t['risk'] <= 35:
            return '안정성'
        if p['economy'] == '빠듯한 편':
            return '수입'
        if t['tradition'] <= 35 and t['risk'] >= 50:
            return '적성·흥미'
        return None
    if question_id == 'leisure':
        if '배우자·자녀' in p['family'] or '3세대' in p['family'] or '자녀와 함께' in p['family']:
            return '가족'
        if t['extraversion'] <= 35 and p['family'] == '1인 가구':
            return '혼자'
        if t['extraversion'] >= 65 and p['marital'] == '미혼':
            return '친구·연인'
        return None
    if question_id == 'marriage':
        if t['tradition'] >= 65 and (p['marital'] == '기혼' or p['age'] >= 50):
            return {'반드시 해야 한다', '하는 것이 좋다'}
        if t['tradition'] <= 35 and p['marital'] == '미혼':
            return '해도 좋고 안 해도 좋다'
        return None
    raise ValueError(question_id)


def matches(exp, choice: str) -> bool:
    return choice in exp if isinstance(exp, set) else choice == exp
